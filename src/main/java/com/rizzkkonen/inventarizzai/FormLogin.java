    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String user = txtUser.getText().trim();
        String pwd  = new String(txtPwd.getPassword());

        if (user.isEmpty() || pwd.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username dan Password wajib diisi!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Query tarik semua data user termasuk role
        String sql = "SELECT user_id, user, role FROM users WHERE user = ? AND pwd = ?";

        try (Connection conn = Koneksi.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, user);
            ps.setString(2, pwd);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    // 1. Ambil data dari Result Set
                    int id = rs.getInt("user_id");
                    String username = rs.getString("user");
                    String role = rs.getString("role");

                    // 2. Simpan ke UserSession otomatis (bebas pilih role di GUI)
                    UserSession.setSession(id, username, role);

                    JOptionPane.showMessageDialog(this, "Login Berhasil sebagai: " + role.toUpperCase());

                    // 3. Routing Tampilan Berdasarkan Role Otomatis
                    if ("admin".equalsIgnoreCase(role)) {
                        new FormDashboardAdmin().setVisible(true);
                    } else {
                        // Kalau ada Frame terpisah buat User Biasa, panggil di sini
                        // new FormDashboardUser().setVisible(true);
                        new FormDashboardAdmin().setVisible(true); // Sementara panggil ini dulu
                    }

                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(this, "Username atau Password Salah!", "Login Failure", JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

