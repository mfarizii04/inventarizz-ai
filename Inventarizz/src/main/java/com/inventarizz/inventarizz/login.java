    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        
        String usernameInput = user.getText().trim();
        String passwordInput = pwd.getText().trim();

        // 1. Validasi Input Kosong
        if (usernameInput.isEmpty() || passwordInput.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Username dan Password tidak boleh kosong!", 
                "Peringatan", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Logika Cek ke Database MySQL
        String sql = "SELECT * FROM akun WHERE username = ? AND password = ?";

        try (Connection conn = Koneksi.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, usernameInput);
            ps.setString(2, passwordInput);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    String namaAdmin = rs.getString("nama_lengkap");
                    
                    JOptionPane.showMessageDialog(this, 
                        "Selamat datang, " + namaAdmin + "!", 
                        "Login Berhasil", 
                        JOptionPane.INFORMATION_MESSAGE);

                    // TODO: Buka Main Menu / Dashboard Form
                    // example:
                    // new DashboardForm().setVisible(true);
                    
                    // Tutup Form Login
                    this.dispose();
                } else {
                    JOptionPane.showMessageDialog(this, 
                        "Username atau Password salah!", 
                        "Login Gagal", 
                        JOptionPane.ERROR_MESSAGE);
                    
                    // Reset field password & set focus back to username
                    pwd.setText("");
                    user.requestFocus();
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, 
                "Terjadi kesalahan database: " + e.getMessage(), 
                "Database Error", 
                JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
        
    }//GEN-LAST:event_btnLoginActionPerformed

